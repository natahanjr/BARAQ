#: Stag(es) whose presence makes the chain a *completed* campaign even when
#: only two families fired (exfiltration / lateral movement / C2).
TERMINAL_STAGES = {"Exfiltration / C2", "Lateral Movement"}

CORRELATION_THRESHOLD = 2  # distinct rule families -> correlated alert
MAX_STAGE_GAP_MINUTES = 60  # chain gap beyond which the chain is "slow burn"


class KillChainCorrelationRule(BaseRule):
    rule_id = "kill_chain_correlation"
    name = "Multi-Stage Attack Chain Detected"
    description = (
        "Multiple independent detection signals fired for the same user or "
        "source within the window, indicating a multi-stage attack campaign "
        "rather than isolated incidents."
    )
    severity = "critical"
    confidence = 0.85
    mitre_id = "T1071"
    recommendation = (
        "Treat this as a coordinated incident. Correlate the evidence events, "
        "assume deeper compromise, isolate affected hosts and rotate all "
        "affected credentials."
    )

    def __init__(
        self,
        session,
        threshold: int = CORRELATION_THRESHOLD,
        window_minutes: int = 60,
        max_stage_gap_minutes: int = MAX_STAGE_GAP_MINUTES,
    ):
        super().__init__(session)
        self.threshold = threshold
        self.window_minutes = window_minutes
        self.max_stage_gap_minutes = max_stage_gap_minutes

    def evaluate(self, window_minutes: int) -> list[DetectionResult]:
        since = datetime.now(timezone.utc) - timedelta(minutes=self.window_minutes or window_minutes)
        findings: list[DetectionResult] = []

        alerts = self.session.scalars(
            select(Alert).where(
                Alert.created_at >= since,
                Alert.status == "open",
                *self._org_conds(Alert),
            )
        ).all()

        by_group: dict[str, dict[str, datetime]] = {}
        for alert in alerts:
            key = self._group_key(alert)
            if key is None:
                continue
            stage = KILL_CHAIN_STAGES.get(alert.rule, "Other")
            first_seen = by_group.setdefault(key, {}).get(stage)
            created = alert.created_at
            if first_seen is None or (created is not None and created < first_seen):
                by_group[key][stage] = created

        for key, stages in by_group.items():
            if len(stages) < self.threshold:
                continue
            sequence, span_min, max_gap_min, ordered_ratio = self._timeline(stages)
            has_terminal = bool({s for s in stages} & TERMINAL_STAGES)
            ordered = True if ordered_ratio == 1.0 and len(sequence) > 1 else False
            slow = span_min > self.max_stage_gap_minutes
            evidence = (
                f"{len(stages)} independent detections correlated for '{key}' "
                f"({', '.join(sequence)}); "
                f"chain span {span_min:.1f} min, max inter-stage gap {max_gap_min:.1f} min"
            )
            if ordered:
                evidence += "; stages follow the canonical kill-chain order"
            elif len(sequence) > 1:
                evidence += f"; ordering deviates from the canonical sequence ({ordered_ratio:.0%} of adjacent pairs advance)"
            if slow:
                evidence += "; slow-burn chain (span exceeds stage-gap budget)"
            if has_terminal:
                evidence += "; includes a terminal stage (exfiltration/lateral movement)"
            confidence = min(0.98, 0.6 + len(stages) * 0.08 + (0.05 if ordered else 0.0))
            if slow and len(stages) <= self.threshold:
                confidence = max(0.5, confidence - 0.1)
            findings.append(
                self._result(
                    evidence=evidence,
                    event_ids=[],
                    severity="critical" if (has_terminal or len(stages) >= 3) else "high",
                    confidence=confidence,
                )
            )
        return findings

    @staticmethod
    def _timeline(stages: dict[str, datetime]) -> tuple[list[str], float, float, float]:
        """(ordered stage names, total span in minutes, max inter-stage gap,
        fraction of adjacent pairs advancing in canonical order).

        Only stages carrying a timestamp contribute to the timing analysis;
        stages without timestamps are appended at the end of the sequence.
        """
        order_index = {name: i for i, name in enumerate(KILL_CHAIN_STAGES.values())}
        timed = [(ts, name) for name, ts in stages.items() if ts is not None]
        timed.sort(key=lambda pair: pair[0])
        sequence = [name for _, name in sorted(timed, key=lambda pair: pair[0])]
        untimed = [name for name in stages if name not in sequence]
        sequence.extend(untimed)

        if len(timed) < 2:
            return sequence, 0.0, 0.0, 1.0 if len(sequence) <= 1 else 0.0

        first = timed[0][0]
        last = timed[-1][0]
        span_min = (last - first).total_seconds() / 60.0
        max_gap = 0.0
        for (t1, _), (t2, _) in zip(timed, timed[1:]):
            max_gap = max(max_gap, (t2 - t1).total_seconds() / 60.0)

        ordered_steps = 0
        # "Discovery" is phase-agnostic (recon legitimately precedes or sits
        # inside a campaign), so it is excluded from the strict ordering
        # pairwise check while still being reported in the timeline.
        strict = [s for s in sequence if s != "Discovery"]
        index_seq = [order_index.get(s, 9999) for s in strict]
        for a, b in zip(index_seq, index_seq[1:]):
            if b > a:
                ordered_steps += 1
        ratio = ordered_steps / max(len(index_seq) - 1, 1)
        return sequence, float(span_min), float(max_gap), float(ratio)

    @staticmethod
    def _group_key(alert: Alert) -> str | None:
        import re

        m = re.search(r"account '([^']+)'", alert.evidence)
        if m:
            return f"user:{m.group(1)}"
        m = re.search(r"from (\d{1,3}(?:\.\d{1,3}){3})", alert.evidence)
        if m:
            return f"ip:{m.group(1)}"
        return None
