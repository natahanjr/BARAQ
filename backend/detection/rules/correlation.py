"""Rule - Multi-Stage Kill-Chain Correlation (timing-composed).

Correlates otherwise-independent detections into a multi-stage incident.
If several rule families fired for the same user or host within the
window, a higher-severity correlated alert is raised (e.g. brute-force ->
persistence -> lateral movement).

Timing composition (v2): beyond counting stage families, the rule now
reconstructs the *observed sequence* per host/user - each stage's first
alert - and measures two timing facts from the timeline:

* **Ordering** - the fraction of adjacent stage pairs that advance along
  the canonical kill-chain order (``KILL_CHAIN_STAGES``). A chain whose
  stages arrive in expected order (discovery -> execution -> persistence
  -> exfiltration) is a coherent campaign; a reversed or scrambled
  sequence is more likely coincident telemetry and is scored lower.
* **Gap** - the wall-clock span of the chain and the longest gap between
  consecutive stages. A chain with isolated fast sub-steps but a very
  slow overall span is still a chain, but a "slow burn" and fired with
  a softer confidence.

Pure-live: operates on real alerts generated by the live pipeline.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone

from sqlalchemy import select

from backend.database.models import Alert
from backend.detection.rules.base import BaseRule, DetectionResult

